(function () {
  let seq = 0;

  function renderItem(accId, item) {
    const n = ++seq;
    return `<div class="accordion-item faq-item" data-kw="${(item.kw || "").replace(/"/g, "&quot;")}">
      <h2 class="accordion-header"><button class="accordion-button collapsed" type="button"
        data-bs-toggle="collapse" data-bs-target="#${accId}-i${n}">${item.q}</button></h2>
      <div id="${accId}-i${n}" class="accordion-collapse collapse" data-bs-parent="#${accId}">
        <div class="accordion-body">${item.a}</div>
      </div>
    </div>`;
  }

  /** Renders FAQ sections into rootEl; binds live search on searchInput (optional). */
  window.renderFaqInto = function (rootEl, searchInput) {
    if (!rootEl || rootEl.dataset.rendered === "1") return;
    const html = FAQ_SECTIONS.map((sec) => `
      <h5 class="mt-4 text-primary">${sec.title}</h5>
      <div class="accordion mb-3" id="${sec.id}">
        ${sec.items.map((it) => renderItem(sec.id, it)).join("")}
      </div>`).join("");
    rootEl.innerHTML = html;
    rootEl.dataset.rendered = "1";

    if (searchInput) {
      searchInput.addEventListener("input", () => {
        const q = searchInput.value.trim().toLowerCase();
        rootEl.querySelectorAll(".faq-item").forEach((item) => {
          const hay = (item.textContent + " " + (item.dataset.kw || "")).toLowerCase();
          item.classList.toggle("d-none", !!q && !hay.includes(q));
        });
        rootEl.querySelectorAll("h5.text-primary").forEach((h) => {
          const acc = h.nextElementSibling;
          const visible = acc ? acc.querySelectorAll(".faq-item:not(.d-none)").length : 0;
          h.classList.toggle("d-none", !!q && visible === 0);
          if (acc) acc.classList.toggle("d-none", !!q && visible === 0);
        });
      });
    }
  };
})();
